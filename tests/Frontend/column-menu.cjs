const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../..');
const source = fs.readFileSync(path.join(root,
    'resources/views/components/record-editor/column-header.blade.php'), 'utf8');
const expression = source.match(/x-data="([\s\S]*?)"\s*>/)[1].replaceAll('@js($column)', "'city'");
let requests = [];
const menu = vm.runInNewContext('(' + expression + ')');
const dialog = {open:false,showModal(){this.open=true},close(){this.open=false}};
let restored = 0;
menu.$wire = {tableFilters:{city:'Quito'},filterColumn:async (...args)=>requests.push(args)};
menu.$nextTick = callback => callback();
menu.$refs = {columnMenu:dialog};
menu.showMenu({currentTarget:{focus(){restored++}}});
assert.equal(menu.open, true);
assert.equal(dialog.open, true);
assert.equal(menu.draft, 'Quito');
menu.draft = 'Cuenca';
assert.equal(requests.length, 0, 'Changing the draft must not refresh the table');
(async () => {
    await menu.applyFilter();
    assert.deepEqual(requests, [['city','Cuenca']]);
    assert.equal(dialog.open, false);
    assert.equal(restored, 1);
    menu.showMenu({currentTarget:{focus(){restored++}}});
    menu.closeMenu();
    assert.equal(requests.length, 1, 'Cancel must not apply draft values');
    assert.match(source, /<dialog/);
    assert.match(source, /x-teleport="body"/);
    assert.match(source, /@keydown\.escape\.stop/);
    assert.match(source, /\$wire\.sortColumn/);
    assert.match(source, /\$wire\.groupColumn/);
    console.log('PASS: native filter dialog, staged changes, one apply request, cancellation and focus restoration.');
})().catch(error => {console.error(error);process.exitCode=1});
